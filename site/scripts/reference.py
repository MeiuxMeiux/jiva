#!/usr/bin/env python3
"""reference — GENERATED partial: every `jiva` verb + `just` recipe from `jiva help` / `just --list`.
site-build runs it before build.py; output is gitignored, never hand-edited; drift.py counts it as named.
Usage: reference.py [out]   (default site/src/partials/reference.html)"""
import html, os, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HOME = pathlib.Path(os.environ.get("JIVA_HOME") or ROOT.parent)
OUT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src" / "partials" / "reference.html"
GROUPS = [("j-*", "verb wrappers"), ("site-*", "this page"), ("*", "everything else")]


def run(*cmd):
    out = subprocess.run(cmd, capture_output=True, text=True, cwd=HOME).stdout
    return out if out.strip() else sys.exit(f"site-build: reference.py: no output from {cmd}")


def prose(s):  # escape, then `x` → <code>x</code>
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", html.escape(s, quote=False))


def jiva_rows():
    rows = []
    for line in run(str(HOME / "bin" / "jiva"), "help").splitlines():
        if not re.match(r"  [a-z]", line):
            continue
        m = re.match(r"  (\S.*?)\s{2,}(\S.*)$", line)
        use, text = (m.group(1), m.group(2)) if m else (line[2:21].strip(), line[21:].strip())
        name, _, args = use.partition(" ")
        if "|" in name:   # claim|report|… share one help line
            rows += [(n, "", f"{text}; see Six verbs") for n in name.split("|")]
        else:
            rows.append((name, args, text))
    return rows


def just_rows():
    rows = []
    for line in run("just", "--list").splitlines()[1:]:
        use, _, text = line.strip().partition("# ")
        name, _, args = use.strip().partition(" ")
        if name and name != "default":
            rows.append((name, args.strip(), text.strip()))
    return rows


def row(tool, name, args, text):
    extra = f' <span class="arg">{html.escape(args, quote=False)}</span>' if args else ""
    return f'      <tr><td><code>{tool} {name}{extra}</code></td><td>{prose(text)}</td></tr>\n'


def table(caption, head, body):
    return (f'  <div class="scroll"><table>\n    <caption>{caption}</caption>\n'
            f'    <thead><tr><th scope="col">{head}</th><th scope="col">what it does</th></tr></thead>\n'
            f'{body}  </table></div>\n')


def main():
    jv = "".join(row("jiva", *r) for r in jiva_rows())
    left, body = just_rows(), ""
    for pat, label in GROUPS:
        got, left = ([r for r in left if r[0].startswith(pat[:-1])],  # "*"[:-1] == "" takes the rest
                     [r for r in left if not r[0].startswith(pat[:-1])])
        body += (f'    <tbody>\n      <tr class="grp"><th colspan="2" scope="rowgroup">{pat} · {label}</th></tr>\n'
                 + "".join(row("just", *r) for r in got)
                 + "    </tbody>\n")
    page = ('<!-- GENERATED by site/scripts/reference.py at site-build. Do not edit; gitignored. -->\n'
            '<section class="band" id="reference">\n'
            '  <h2><span class="num">09</span>Reference</h2>\n'
            '  <p class="wide">Every verb and recipe, read from <code>jiva help</code> and '
            '<code>just --list</code> when this page was built. Nothing here is typed by hand.</p>\n'
            '  <div class="ref">\n'
            + table("jiva verbs", "verb", f"    <tbody>\n{jv}    </tbody>\n")
            + table("just recipes", "recipe", body)
            + '  </div>\n</section>\n')
    OUT.write_text(page, encoding="utf-8")
    print(f"site-build: {OUT.name} ({page.count('<tr>') - 2} rows from jiva help + just --list)")


main()
